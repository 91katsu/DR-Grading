# ---------------- launch: one background queue per GPU ----------------
gpu_queue() {
  local gpu=$1 j
  for j in "${JOBS[@]}"; do
    [ "${j%% *}" = "$gpu" ] && eval "run $j"
  done
}

GPUS=$(for j in "${JOBS[@]}"; do echo "${j%% *}"; done | sort -un)
log "queue: ${#JOBS[@]} experiments on GPU $(echo $GPUS)"
if [ "$DRY_RUN" = 1 ]; then
  for g in $GPUS; do gpu_queue "$g"; done
else
  trap 'log "interrupted, stopping all queues"; kill 0' INT TERM
  for g in $GPUS; do gpu_queue "$g" & done
  wait
fi
log "queue finished"
